@pytest.mark.asyncio
async def test_a_slow_tool_times_out(
    client: httpx.AsyncClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The 1.5 s budget is ours to enforce; ElevenLabs waits at least 5 s."""
    monkeypatch.setattr(loop, "TOOL_TIMEOUT_S", 0.01)
    services = _services()

    async def slow() -> list[RoomType]:
        await asyncio.sleep(1)
        return []

    monkeypatch.setattr(services.hotel, "list_room_types", slow)
    app.dependency_overrides[get_services] = lambda: services

    response = await client.post(
        "/tools/check_availability",
        json=_body(check_in="2027-02-03", check_out="2027-02-05", guests=2),
        headers=HEADERS,
    )

    assert response.json() == {"ok": False, "reason": "tool_timeout"}


@pytest.mark.asyncio
async def test_the_call_id_keys_a_retried_booking(client: httpx.AsyncClient) -> None:
    """call_id is bound to system__conversation_id: a retry books once."""
    booking = _body(
        room_type="Superior",
        check_in=str(date(2027, 2, 3)),
        check_out=str(date(2027, 2, 5)),
        adults=2,
        first_name="Giulia",
        last_name="Rossi",
        language="it",
    )

    first = await client.post("/tools/create_booking", json=booking, headers=HEADERS)
    again = await client.post("/tools/create_booking", json=booking, headers=HEADERS)

    assert first.json()["ok"] is True
    assert again.json()["reference"] == first.json()["reference"]


@pytest.mark.asyncio
async def test_each_request_is_a_trace_in_the_call_session(
    client: httpx.AsyncClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Webhook traces join the call's Langfuse session, keyed by call_id."""
    fake = FakeClient()
    monkeypatch.setattr(observability, "_get_client", lambda: fake)
    propagated: list[dict[str, Any]] = []

    @contextmanager
    def fake_propagate(**kwargs: Any) -> Iterator[None]:
        propagated.append(kwargs)
        yield

    monkeypatch.setattr(observability, "propagate_attributes", fake_propagate)

    await client.post("/tools/get_guest_info", json=_body(), headers=HEADERS)

    assert propagated == [
        {
            "session_id": "conv-1",
            "trace_name": "handle-tool-webhook",
            "tags": ["lang:unknown"],
        }
    ]
    trace, tool = fake.observations
    assert trace.started["name"] == "handle-tool-webhook"
    assert tool.started["name"] == "get_guest_info"


def _booking_body(**overrides: object) -> dict[str, object]:
    fields: dict[str, object] = {
        "room_type": "Superior",
        "check_in": str(date(2027, 2, 3)),
        "check_out": str(date(2027, 2, 5)),
        "adults": 2,
        "first_name": "Giulia",
        "last_name": "Rossi",
        "language": "it",
    }
    fields.update(overrides)
    return _body(**fields)


@pytest.mark.asyncio
async def test_any_tool_call_opens_the_call_log_entry(
    client: httpx.AsyncClient, services: Services
) -> None:
    """A call that used a tool is logged, even when nothing was booked."""
    await client.post("/tools/get_guest_info", json=_body(), headers=HEADERS)

    entry = await services.calls.get("conv-1")
    assert entry is not None
    assert (entry.outcome, entry.language, entry.reference) == (None, None, None)
    assert entry.needs_followup is False


@pytest.mark.asyncio
async def test_a_booking_is_logged_with_its_reference_and_language(
    client: httpx.AsyncClient, services: Services
) -> None:
    """The call log keeps the outcome and the booking, by id only."""
    response = await client.post(
        "/tools/create_booking", json=_booking_body(), headers=HEADERS
    )

    entry = await services.calls.get("conv-1")
    assert entry is not None
    assert entry.outcome == "booked"
    assert entry.language == "it"
    assert entry.reference == response.json()["reference"]


